import { spawn } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { chromium } from "playwright-core";

const root = resolve(import.meta.dirname, "..");
const port = Number(process.env.SOUNDTRACK_PROFILE_PORT ?? 4189);
const durationSeconds = Math.max(3, Number(process.env.SOUNDTRACK_PROFILE_SECONDS ?? 20));
const server = spawn("pnpm", ["dev", "--host", "127.0.0.1", "--port", String(port)], {
  cwd: root,
  stdio: "ignore",
});
const profiles = [
  { title: "Desktop Chrome", viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 },
  { title: "Mobile Chrome proxy", viewport: { width: 393, height: 852 }, deviceScaleFactor: 3, hasTouch: true, isMobile: true },
];

try {
  const url = `http://127.0.0.1:${port}/drive/labs/soundtrack/`;
  await waitForServer(url);
  const browser = await chromium.launch({
    headless: true,
    executablePath: chromeExecutable(),
    args: ["--autoplay-policy=no-user-gesture-required"],
  });
  const results = [];
  try {
    for (const profile of profiles) {
      const context = await browser.newContext(profile);
      const page = await context.newPage();
      const errors = [];
      page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
      page.on("pageerror", (error) => errors.push(error.message));
      const cdp = await context.newCDPSession(page);
      await cdp.send("Performance.enable");
      await page.goto(url, { waitUntil: "networkidle" });
      await page.locator("#start-audio").click();
      await page.locator("#start-audio").filter({ hasText: "Soundtrack running" }).waitFor();
      await page.locator("#vehicle-scenario").selectOption("linked");
      await page.locator("#chase-tier").selectOption("3");
      await page.locator("#speed").fill("95");
      await page.locator("#drift").fill("70");
      const before = metrics(await cdp.send("Performance.getMetrics"));
      await page.waitForTimeout(durationSeconds * 1_000);
      const after = metrics(await cdp.send("Performance.getMetrics"));
      results.push({
        title: profile.title,
        taskUtilization: (after.TaskDuration - before.TaskDuration) / durationSeconds,
        scriptUtilization: (after.ScriptDuration - before.ScriptDuration) / durationSeconds,
        heapMb: after.JSHeapUsedSize / 1024 / 1024,
        errors,
      });
      await context.close();
    }
  } finally {
    await browser.close();
  }
  await mkdir(join(root, "reports"), { recursive: true });
  const report = renderReport(results);
  const reportPath = join(root, "reports", "soundtrack-performance.md");
  await writeFile(reportPath, report, "utf8");
  process.stdout.write(`${report}\nReport: ${reportPath}\n`);
  if (results.some((result) => result.taskUtilization > 0.35 || result.heapMb > 100 || result.errors.length > 0)) {
    process.exitCode = 1;
  }
} finally {
  server.kill("SIGTERM");
}

function metrics(response) {
  return Object.fromEntries(response.metrics.map((metric) => [metric.name, metric.value]));
}

function renderReport(results) {
  const rows = results.map((result) => `| ${result.title} | ${(result.taskUtilization * 100).toFixed(1)}% | ${(result.scriptUtilization * 100).toFixed(1)}% | ${result.heapMb.toFixed(1)} MB | ${result.errors.length} |`).join("\n");
  return `# Soundtrack Runtime Profile\n\nGenerated by \`pnpm soundtrack:profile\` while running the complete linked-drift, Chase-tier-3 mix.\n\n| Profile | Main-thread task utilization | Script utilization | JS heap | Browser errors |\n|---|---:|---:|---:|---:|\n${rows}\n\nThe mobile result is Chrome device emulation and catches layout/main-thread regressions; it is not a substitute for physical-device or Safari audio-thread testing. AudioWorklet rendering occurs off the main thread, so final crackle/dropout validation remains a listening test.\n`;
}

async function waitForServer(url) {
  for (let attempt = 0; attempt < 80; attempt += 1) {
    try { if ((await fetch(url)).ok) return; } catch { /* still starting */ }
    await new Promise((resolveDelay) => setTimeout(resolveDelay, 250));
  }
  throw new Error("Timed out waiting for Soundtrack Lab.");
}

function chromeExecutable() {
  if (process.env.CHROME_PATH) return process.env.CHROME_PATH;
  if (process.platform === "darwin") return "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
  return "/usr/bin/google-chrome";
}
